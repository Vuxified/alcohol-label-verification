CASES = []


def add(section, field, typed, label, expected, reason, bev="spirits", **extra):
    CASES.append((section, field, bev, typed, label if isinstance(label, list) else [label], expected, reason, extra))


from app.verify.abv import parse_typed_abv


def web_abv(value):
    """What app/web/main.py does with the typed alcohol content."""
    v = (value or "").strip()
    if not v:
        return None
    x = parse_typed_abv(v)
    return ERR if x is None else x


def run(section, field, bev, typed, lines, extra):
    kw = {"beverage_type": bev, "brand_name": "Old Tom Distillery"}
    if field == "abv":
        x = web_abv(typed)
        if x == ERR:
            return ERR, "form rejects it"
        kw["abv"] = x
        kw["brand_name"] = "Old Tom"
    elif field == "proof":
        kw["abv"] = web_abv(extra.get("abv", "45")); kw["brand_name"] = "Old Tom"
    elif field == "net_contents":
        kw["net_contents"] = typed; kw["brand_name"] = "Old Tom"
    elif field == "country_of_origin":
        kw["source"] = "imported"; kw["country_of_origin"] = typed; kw["brand_name"] = "Old Tom"
    else:
        kw[field] = typed
    kw.update(extra.get("app", {}))
    rep = verify(Application(**kw), lines)
    r = rep.get(field)
    return r.verdict.value, f"{r.code or ''} {r.reason}"


